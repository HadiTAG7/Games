# ── التحقق والكتابة ───────────────────────────────────────────────────────────

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "data" / "feud.json"
MIN_QUESTIONS = 140
MIN_ANSWERS, MAX_ANSWERS = 5, 8
MIN_POINTS = 2
MIN_TOTAL, MAX_TOTAL = 75, 100
MAX_WORDS = 3  # an answer is at most three words
MAX_ALT = 4
MARKS = re.compile("[\u0610-\u061a\u064b-\u065f\u0670\u06d6-\u06ed\u0640]")  # diacritics, tatweel
LETTERS = str.maketrans({"أ": "ا", "إ": "ا", "آ": "ا", "ٱ": "ا", "ة": "ه", "ى": "ي"})


def normalise(text):
    """Comparison key: no diacritics, one hamza/ta-marbuta form, no leading «ال», no spaces."""
    words = MARKS.sub("", text).translate(LETTERS).split()
    return "".join(w[2:] if w.startswith("ال") and len(w) > 3 else w for w in words)


def check(questions):
    problems = []
    if len(questions) < MIN_QUESTIONS:
        problems.append(f"only {len(questions)} questions (need {MIN_QUESTIONS})")
    seen_q = {}
    for n, entry in enumerate(questions, 1):
        label = f"#{n}"
        if not (isinstance(entry, tuple) and len(entry) == 2):
            problems.append(f"{label}: must be (question, answers)")
            continue
        q, answers = entry
        if not isinstance(q, str) or not q.strip() or q != q.strip():
            problems.append(f"{label}: question must be a trimmed, non-empty string")
            continue
        label = f"#{n} «{q}»"
        key = normalise(q)
        if key in seen_q:
            problems.append(f"{label}: same question as #{seen_q[key]}")
        seen_q.setdefault(key, n)
        if not isinstance(answers, list) or not MIN_ANSWERS <= len(answers) <= MAX_ANSWERS:
            count = len(answers) if isinstance(answers, list) else "no"
            problems.append(f"{label}: {count} answers (need {MIN_ANSWERS}-{MAX_ANSWERS})")
            if not isinstance(answers, list):
                continue
        owner = {}  # comparison key -> index of the answer it belongs to
        previous = None
        total = 0
        for i, item in enumerate(answers):
            if not (isinstance(item, tuple) and len(item) == 3):
                problems.append(f"{label}: answer {i + 1} must be (answer, points, alt)")
                continue
            a, points, alt = item
            if not isinstance(a, str) or not a.strip() or a != a.strip():
                problems.append(f"{label}: answer {i + 1} must be a trimmed, non-empty string")
                continue
            if len(a.split()) > MAX_WORDS:
                problems.append(f"{label}: «{a}» is longer than {MAX_WORDS} words")
            if not isinstance(points, int) or isinstance(points, bool) or points < MIN_POINTS:
                problems.append(f"{label}: «{a}» points must be a whole number ≥ {MIN_POINTS}")
            else:
                if previous is not None and points >= previous:
                    problems.append(f"{label}: «{a}» has {points} points, not below {previous}")
                previous = points
                total += points
            key = normalise(a)
            if key in owner:
                problems.append(f"{label}: «{a}» repeats another answer")
            owner[key] = i
            if not isinstance(alt, list) or len(alt) > MAX_ALT:
                problems.append(f"{label}: «{a}» alt must be a list of at most {MAX_ALT}")
                continue
            if len(set(alt)) != len(alt):
                problems.append(f"{label}: «{a}» has a repeated alt")
            for v in alt:
                if not isinstance(v, str) or not v.strip() or v != v.strip():
                    problems.append(f"{label}: «{a}» has an empty or untrimmed alt")
                elif v == a:
                    problems.append(f"{label}: «{a}» lists itself in alt")
        # An alt may not point at a different answer of the same question.
        for i, item in enumerate(answers):
            if not (isinstance(item, tuple) and len(item) == 3 and isinstance(item[2], list)):
                continue
            for v in item[2]:
                if not isinstance(v, str):
                    continue
                other = owner.get(normalise(v), i)
                if other != i:
                    problems.append(f"{label}: alt «{v}» of «{item[0]}» matches «{answers[other][0]}»")
                owner.setdefault(normalise(v), i)
        if not MIN_TOTAL <= total <= MAX_TOTAL:
            problems.append(f"{label}: points add up to {total} (need {MIN_TOTAL}-{MAX_TOTAL})")
    return problems


def main():
    problems = check(QUESTIONS)
    if problems:
        raise SystemExit("feud_questions.py: the question bank has problems:\n" + "\n".join(problems))
    questions = [
        {
            "id": f"f{n:03d}",
            "q": q,
            "answers": [{"a": a, "points": p, "alt": list(alt)} for a, p, alt in answers],
        }
        for n, (q, answers) in enumerate(QUESTIONS, 1)
    ]
    OUT.write_text(json.dumps({"questions": questions}, ensure_ascii=False, indent=1) + "\n")
    eight = sum(len(q["answers"]) == MAX_ANSWERS for q in questions)
    print(f"{len(questions)} questions ({eight} with {MAX_ANSWERS} answers) written to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
