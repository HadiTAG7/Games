# ── التحقق والكتابة ───────────────────────────────────────────────────────────

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "data" / "truth.json"
MIN_STATEMENTS = 280
MAX_CHARS = 110  # for both the statement and `why`
MIN_TRUE, MAX_TRUE = 0.45, 0.55  # share of true statements
ID = re.compile(r"t\d{3,}")
MARKS = re.compile("[ؐ-ًؚ-ٰٟۖ-ۭـ]")  # diacritics, tatweel
LETTERS = str.maketrans({"أ": "ا", "إ": "ا", "آ": "ا", "ٱ": "ا", "ة": "ه", "ى": "ي"})
NOT_WORD = re.compile(r"[^\w]")  # spaces and punctuation such as «» ( ) : ،


def normalise(text):
    """Comparison key: no diacritics, one alif/ta-marbuta/ya form, no spaces or punctuation."""
    return NOT_WORD.sub("", MARKS.sub("", text).translate(LETTERS))


def build(sections):
    """Flatten the sections into JSON records with ids t001, t002, …; collect shape problems."""
    problems, records = [], []
    for n, section in enumerate(sections, 1):
        if not (isinstance(section, tuple) and len(section) == 2 and isinstance(section[1], list)):
            problems.append(f"section #{n}: must be (category, [(statement, answer, why), ...])")
            continue
        category, entries = section
        for entry in entries:
            label = f"#{len(records) + 1}"
            if not (isinstance(entry, tuple) and len(entry) == 3):
                problems.append(f"{label} in «{category}»: must be (statement, answer, why)")
                entry = (entry, None, None)
            s, a, why = entry
            records.append({"id": f"t{len(records) + 1:03d}", "s": s, "a": a, "why": why, "category": category})
    return records, problems


def check(records):
    problems = []
    if len(records) < MIN_STATEMENTS:
        problems.append(f"only {len(records)} statements (need {MIN_STATEMENTS})")
    seen_id, seen_s = set(), {}
    for r in records:
        label = r["id"] if isinstance(r["id"], str) else repr(r["id"])
        if not isinstance(r["id"], str) or not ID.fullmatch(r["id"]):
            problems.append(f"{label}: id must look like t001")
        elif r["id"] in seen_id:
            problems.append(f"{label}: repeated id")
        seen_id.add(r["id"])
        s, a, why = r["s"], r["a"], r["why"]
        if not isinstance(s, str) or not s.strip() or s != s.strip():
            problems.append(f"{label}: statement must be a trimmed, non-empty string")
            s = None
        else:
            label = f"{label} «{s}»"
            if len(s) > MAX_CHARS:
                problems.append(f"{label}: statement is {len(s)} characters (max {MAX_CHARS})")
            key = normalise(s)
            if key in seen_s:
                problems.append(f"{label}: same statement as {seen_s[key]}")
            seen_s.setdefault(key, r["id"])
        if not isinstance(a, bool):
            problems.append(f"{label}: answer must be True or False")
        if not isinstance(why, str) or not why.strip() or why != why.strip():
            problems.append(f"{label}: why must be a trimmed, non-empty string")
        else:
            if len(why) > MAX_CHARS:
                problems.append(f"{label}: why is {len(why)} characters (max {MAX_CHARS})")
            if isinstance(a, bool) and why.startswith("نعم") != a:
                problems.append(f"{label}: why should start with «نعم» exactly when the answer is True")
        if r["category"] not in CATEGORIES:
            problems.append(f"{label}: unknown category «{r['category']}»")
    used = {r["category"] for r in records}
    for category in CATEGORIES:
        if category not in used:
            problems.append(f"category «{category}» has no statements")
    if records:
        share = sum(r["a"] is True for r in records) / len(records)
        if not MIN_TRUE <= share <= MAX_TRUE:
            problems.append(f"{share:.0%} of statements are true (need {MIN_TRUE:.0%}-{MAX_TRUE:.0%})")
    return problems


def main():
    records, problems = build(STATEMENTS)
    problems += check(records)
    if problems:
        raise SystemExit("truth_questions.py: the statement bank has problems:\n" + "\n".join(problems))
    OUT.write_text(json.dumps({"questions": records}, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    true = sum(r["a"] for r in records)
    print(f"{len(records)} statements ({true} true, {len(records) - true} false, "
          f"{len(CATEGORIES)} categories) written to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
