# ── التحقق والكتابة ───────────────────────────────────────────────────────────

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "data" / "who.json"
MIN_QUESTIONS = 150
MAX_LENGTH = 80
QUESTION_MARK = "؟"
ID = re.compile(r"w\d{3}")
LATIN = re.compile(r"[A-Za-z]")
MARKS = re.compile("[ؐ-ًؚ-ٰٟۖ-ۭـ]")  # diacritics, tatweel
PUNCTUATION = re.compile(r"[\s«»\"'؟?!،,.…:؛-]")
LETTERS = str.maketrans({"أ": "ا", "إ": "ا", "آ": "ا", "ٱ": "ا", "ة": "ه", "ى": "ي"})


def normalise(text):
    """Comparison key: no diacritics, one alef/ta-marbuta/ya form, no spaces or punctuation."""
    return PUNCTUATION.sub("", MARKS.sub("", text).translate(LETTERS))


def build(entries):
    return [
        {"id": f"w{n:03d}", "q": q, "category": category}
        for n, (q, category) in enumerate(entries, 1)
    ]


def check(entries):
    problems = []
    if len(entries) < MIN_QUESTIONS:
        problems.append(f"only {len(entries)} prompts (need {MIN_QUESTIONS})")
    for n, entry in enumerate(entries, 1):
        if not (isinstance(entry, tuple) and len(entry) == 2):
            problems.append(f"#{n}: must be (prompt, category)")
    if problems:
        return problems  # the rest assumes well-formed entries

    seen_q = {}
    used = set()
    ids = set()
    for item in build(entries):
        qid, q, category = item["id"], item["q"], item["category"]
        if not ID.fullmatch(qid) or qid in ids:
            problems.append(f"{qid}: id is malformed or repeated")
        ids.add(qid)
        if not isinstance(q, str) or not q.strip() or q != q.strip():
            problems.append(f"{qid}: prompt must be a trimmed, non-empty string")
            continue
        label = f"{qid} «{q}»"
        if not q.startswith("مين"):
            problems.append(f"{label}: must start with «مين» (it asks about a player)")
        if not q.endswith(QUESTION_MARK):
            problems.append(f"{label}: must end with «{QUESTION_MARK}»")
        if len(q) > MAX_LENGTH:
            problems.append(f"{label}: {len(q)} characters (max {MAX_LENGTH})")
        if "  " in q:
            problems.append(f"{label}: has a double space")
        if LATIN.search(q):
            problems.append(f"{label}: has Latin letters")
        key = normalise(q)
        if key in seen_q:
            problems.append(f"{label}: same prompt as {seen_q[key]}")
        seen_q.setdefault(key, qid)
        if not isinstance(category, str) or not category.strip():
            problems.append(f"{label}: category is empty")
        elif category not in CATEGORIES:
            problems.append(f"{label}: category «{category}» is not in CATEGORIES")
        else:
            used.add(category)
    for category in CATEGORIES:
        if LATIN.search(category):
            problems.append(f"category «{category}» has Latin letters")
        if category not in used:
            problems.append(f"category «{category}» has no prompts")
    return problems


def main():
    problems = check(QUESTIONS)
    if problems:
        raise SystemExit("who_questions.py: the prompt bank has problems:\n" + "\n".join(problems))
    questions = build(QUESTIONS)
    OUT.write_text(json.dumps({"questions": questions}, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    counts = "، ".join(f"{c} {sum(q['category'] == c for q in questions)}" for c in CATEGORIES)
    print(f"{len(questions)} prompts in {len(CATEGORIES)} categories ({counts}) written to {OUT.relative_to(ROOT)}")


